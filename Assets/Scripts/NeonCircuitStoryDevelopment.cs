    private bool storyDialogueIsDebrief;

    private StoryDialogueLine[] ActiveStoryDialogue
    {
        get
        {
            if (!storyDialogueIsDebrief)
            {
                return ActiveStoryChapter.Dialogue;
            }

            int safeIndex = Mathf.Clamp(storySelectedChapter, 0, StoryDebriefs.Length - 1);
            return StoryDebriefs[safeIndex];
        }
    }

    private void OpenStoryDebrief()
    {
        if (!storyMissionSucceeded)
        {
            return;
        }

        OpenMainMenu();
        storyModeOpen = true;
        storyDialogueIsDebrief = true;
        storyDialogueOpen = true;
        storyDialogueIndex = 0;
        menuAnimationStartedAt = Time.unscaledTime;
        PlayMenuClickSfx();
    }

    private void CompleteStoryDebrief()
    {
        storyDialogueOpen = false;
        storyDialogueIsDebrief = false;
        storyDialogueIndex = 0;
        menuAnimationStartedAt = Time.unscaledTime;

        if (storySelectedChapter >= StoryChapters.Length - 1)
        {
            storyModeOpen = true;
            SelectStoryChapter(StoryChapters.Length - 1);
            return;
        }

        SelectStoryChapter(storySelectedChapter + 1);
        StartSelectedStoryChapter();
    }

    private void CancelActiveStoryDialogue()
    {
        if (storyDialogueIsDebrief)
        {
            CompleteStoryDebrief();
            return;
        }

        storyDialogueOpen = false;
        storyDialogueIndex = 0;
        menuAnimationStartedAt = Time.unscaledTime;
    }
